// ============ Cell ↔ TBP board cell ============

/// Outbound: `Cell` → TBP cell. `Empty` → JSON null; `Block(t)` → `t.as_str()`;
/// `Garbage` → `"G"`.
#[must_use]
pub fn cell_to_tbp(c: &Cell) -> Option<&'static str> {
    match c {
        Cell::Empty => None,
        Cell::Block(t) => Some(t.as_str()),
        Cell::Garbage => Some("G"),
    }
}

/// Inbound: TBP cell → `Cell`. `None` → `Empty`; `Some('G')` → `Garbage`;
/// `Some(piece_letter)` → `Block(piece)`; anything else → `BotError::Protocol`.
///
/// # Errors
///
/// - `BotError::Protocol`: the char is not a recognized piece letter (`'G'` for
///   garbage is handled separately).
pub fn cell_from_tbp(c: Option<char>) -> Result<Cell, BotError> {
    match c {
        None => Ok(Cell::Empty),
        Some('G') => Ok(Cell::Garbage),
        Some(c) => MinoType::from_char(c)
            .map(Cell::Block)
            .ok_or_else(|| BotError::Protocol(format!("unknown cell char: {c:?}"))),
    }
}

/// Convert a TBP `error` message into our `BotError`.
///
/// TBP has one known reason (`unsupported_rules`). Any other error
/// reason — including `MaybeUnknown::Unknown` from a future-spec bot —
/// is treated as a protocol violation.
#[must_use]
pub fn tbp_error_to_bot(e: &TbpError) -> BotError {
    match e.reason {
        MaybeUnknown::Known(ErrorCause::UnsupportedRules) => {
            BotError::Protocol("bot does not support our rules".into())
        }
        MaybeUnknown::Unknown(_) => BotError::Protocol("unknown error reason from bot".into()),
        MaybeUnknown::Known(_) => BotError::Protocol("unrecognized error reason from bot".into()),
    }
}
